alter table public.aziende
  add column if not exists cellulare text not null default '',
  add column if not exists telefono_fisso text not null default '',
  add column if not exists processing_status text not null default 'IMPORTATA',
  add column if not exists source_file text not null default '',
  add column if not exists source_row integer,
  add column if not exists import_batch integer,
  add column if not exists import_job_id uuid,
  add column if not exists source_payload jsonb not null default '{}'::jsonb,
  add column if not exists field_provenance jsonb not null default '{}'::jsonb,
  add column if not exists last_enrichment_at timestamptz,
  add column if not exists enrichment_error text not null default '';

create table if not exists public.azienda_tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id),
  azienda_id bigint not null references public.aziende(id) on delete cascade,
  task_type text not null check (task_type in ('CALL','EMAIL','RICERCA_CONTATTO','FOLLOW_UP','APPUNTAMENTO','PROPOSTA')),
  status text not null default 'OPEN' check (status in ('OPEN','IN_PROGRESS','DONE','CANCELLED')),
  destination text not null default '',
  reason text not null default '',
  priority integer not null default 50 check (priority between 0 and 100),
  due_at timestamptz not null default now(),
  completed_at timestamptz,
  outcome text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists azienda_tasks_queue_idx on public.azienda_tasks(status,due_at,priority desc);
create index if not exists azienda_tasks_company_idx on public.azienda_tasks(azienda_id,status);
alter table public.azienda_tasks enable row level security;
revoke all on public.azienda_tasks from anon;
grant select,insert,update,delete on public.azienda_tasks to authenticated;

